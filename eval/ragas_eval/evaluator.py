"""Ragas-compatible evaluation harness for generation and retrieval assessment."""

import logging
from typing import Any, Optional

from eval.generation.lexical_metrics import (
    exact_match_score,
    f1_score,
    rouge_l_score,
    bleu_score,
)
from eval.ragas_eval.judge_factory import BaseJudge, get_judge

logger = logging.getLogger("amg-eval-ragas")


class RagasEvaluator:
    """Evaluates RAG predictions on Faithfulness, Answer Relevancy, Context Precision, and Lexical metrics."""

    def __init__(self, judge: Optional[BaseJudge] = None):
        self.judge = judge or get_judge()

    def evaluate_predictions(self, predictions: list[dict[str, Any]]) -> dict[str, Any]:
        """
        Evaluate a list of model predictions.

        Parameters
        ----------
        predictions:
            List of dicts generated by GenerationRunner containing query, contexts, ground_truth, answer.

        Returns
        -------
        dict:
            Aggregate metrics and detailed per-sample breakdown.
        """
        if not predictions:
            return {"metrics": {}, "sample_scores": []}

        sample_scores: list[dict[str, Any]] = []

        faithfulness_scores: list[float] = []
        relevancy_scores: list[float] = []
        precision_scores: list[float] = []
        em_scores: list[float] = []
        f1_scores: list[float] = []
        rouge_scores: list[float] = []
        bleu_scores: list[float] = []

        for p in predictions:
            query = p.get("query", "")
            answer = p.get("generated_answer", "")
            contexts = p.get("contexts", [])
            full_context_str = "\n".join(contexts) if contexts else ""
            gold_text = p.get("ground_truth_text", "")
            gold_raw = p.get("ground_truth", "")

            # 1. Ragas Grounding / Faithfulness
            faith_score = self.judge.evaluate_faithfulness(query, full_context_str, answer)
            faithfulness_scores.append(faith_score)

            # 2. Ragas Answer Relevancy
            rel_score = self.judge.evaluate_relevancy(query, answer)
            relevancy_scores.append(rel_score)

            # 3. Context Precision
            prec_score = self.judge.evaluate_context_precision(query, contexts, gold_text)
            precision_scores.append(prec_score)

            # 4. Lexical Metrics (against acceptable ground truth candidates)
            candidates = [gold_raw] if isinstance(gold_raw, str) else list(gold_raw) if gold_raw else [""]
            best_em = max(exact_match_score(answer, c) for c in candidates)
            best_f1 = max(f1_score(answer, c) for c in candidates)
            best_rouge = max(rouge_l_score(answer, c) for c in candidates)
            best_bleu = max(bleu_score(answer, c) for c in candidates)

            em_scores.append(best_em)
            f1_scores.append(best_f1)
            rouge_scores.append(best_rouge)
            bleu_scores.append(best_bleu)

            sample_scores.append(
                {
                    "sample_id": p.get("sample_id"),
                    "query": query,
                    "desired_result": {
                        "ground_truth": gold_text,
                        "ground_truth_candidates": candidates,
                        "gold_contexts": p.get("gold_contexts", []),
                    },
                    "generation_output": {
                        "answer": answer,
                        "latency_ms": p.get("latency_ms", 0),
                    },
                    "retrieval_output": {
                        "retrieved_sources": p.get("retrieved_sources", []),
                        "contexts": contexts,
                    },
                    "judge_evaluation": {
                        "faithfulness": faith_score,
                        "relevancy": rel_score,
                        "context_precision": prec_score,
                        "exact_match": best_em,
                        "f1": best_f1,
                        "rouge_l": best_rouge,
                        "bleu_4": best_bleu,
                    },
                    "sample_metadata": p.get("metadata", {}),
                    "is_multimodal": p.get("is_multimodal", False),
                    # Direct top-level access for backward compatibility
                    "answer": answer,
                    "ground_truth": gold_text,
                    "faithfulness": faith_score,
                    "relevancy": rel_score,
                    "context_precision": prec_score,
                    "exact_match": best_em,
                    "f1": best_f1,
                    "rouge_l": best_rouge,
                    "bleu_4": best_bleu,
                    "latency_ms": p.get("latency_ms", 0),
                }
            )

        n = len(predictions)
        metrics = {
            "Faithfulness": round(sum(faithfulness_scores) / n, 4),
            "AnswerRelevancy": round(sum(relevancy_scores) / n, 4),
            "ContextPrecision": round(sum(precision_scores) / n, 4),
            "ExactMatch": round(sum(em_scores) / n, 4),
            "F1": round(sum(f1_scores) / n, 4),
            "ROUGE-L": round(sum(rouge_scores) / n, 4),
            "BLEU-4": round(sum(bleu_scores) / n, 4),
        }

        return {
            "metrics": metrics,
            "sample_scores": sample_scores,
        }
